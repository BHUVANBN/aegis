#!/usr/bin/env node
// Assembles the single-file TXT manual from docs/manual/*.txt prose and the real repository files.
// Usage: node scripts/build-manual.mjs <output.txt>
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const out = process.argv[2] ?? 'AEGIS-Build-Manual.txt';
const sh = (c) => execSync(c, { cwd: root, encoding: 'utf8' });
sh('git add -A');
const EXCLUDE = [/^docs\/manual\//];
const files = sh('git ls-files')
  .split('\n')
  .filter(Boolean)
  .filter((f) => !EXCLUDE.some((r) => r.test(f)))
  .sort();
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const lockHash = crypto
  .createHash('sha256')
  .update(fs.readFileSync(path.join(root, 'package-lock.json')))
  .digest('hex');
const missingProse = [];
const prose = (n) => {
  const p = path.join(root, 'docs/manual', n);
  if (fs.existsSync(p))
    return fs.readFileSync(p, 'utf8').trimEnd().replaceAll('@@LOCKFILE_SHA256@@', lockHash);
  missingProse.push(n);
  return `(prose file ${n} is missing)`;
};

// source-file groups: [section number, title, matcher]
const groups = [
  [
    '7',
    'ROOT, SHARED PACKAGE AND CONFIGURATION FILES',
    (f) =>
      (!f.includes('/') && f !== 'Dockerfile' && f !== 'docker-compose.yml') ||
      f.startsWith('packages/shared/') ||
      f === 'apps/api/package.json' ||
      f === 'apps/api/tsconfig.json',
  ],
  [
    '8',
    'DATABASE SCHEMA, MIGRATIONS AND SEED',
    (f) => f.startsWith('apps/api/src/db/') || f === 'scripts/bootstrap.sql',
  ],
  [
    '10',
    'API IMPLEMENTATION (app, config, auth, Azure adapters, LLM provider)',
    (f) =>
      ['app', 'index', 'config', 'auth', 'util'].some((n) => f === `apps/api/src/${n}.ts`) ||
      f.startsWith('apps/api/src/azure/') ||
      f.startsWith('apps/api/src/llm/'),
  ],
  [
    '11',
    'AGENT IMPLEMENTATIONS AND ORCHESTRATOR; RISK RULES',
    (f) => f.startsWith('apps/api/src/agents/') || f.startsWith('apps/api/src/rules/'),
  ],
  [
    '13',
    'DEPLOYMENT GATE, AUDIT TRAIL AND RECONCILIATION',
    (f) => ['gate', 'audit', 'reconcile'].some((n) => f === `apps/api/src/${n}.ts`),
  ],
  ['14', 'POST-DEPLOYMENT VERIFICATION', (f) => f === 'apps/api/src/verification.ts'],
  ['15', 'FRONTEND IMPLEMENTATION', (f) => f.startsWith('apps/web/') && f !== 'apps/web/Dockerfile'],
  [
    '16',
    'DOCKER AND LOCAL DEVELOPMENT',
    (f) => ['Dockerfile', 'docker-compose.yml', 'apps/web/Dockerfile', 'scripts/local-setup.sh'].includes(f),
  ],
  [
    '17',
    'AZURE INFRASTRUCTURE (BICEP, SAMPLE WORKLOAD, AZURE POLICY, VALIDATION)',
    (f) => f.startsWith('infra/') || f === 'scripts/validate-bicep.sh' || f === 'scripts/policy-setup.sh',
  ],
  ['18', 'ENTRA SETUP SCRIPT', (f) => f === 'scripts/entra-setup.sh'],
  [
    '19',
    'AZURE DEVOPS PIPELINE AND PIPELINE SCRIPTS',
    (f) => f.startsWith('pipelines/') || f.startsWith('pipeline-templates/'),
  ],
  [
    '20',
    'TESTS, FIXTURES AND CHECK RUNNER',
    (f) =>
      f.startsWith('tests/') ||
      ['run-all-checks', 'smoke-test', 'verify-clean-checkout'].some((n) => f === `scripts/${n}.sh`),
  ],
  ['22', 'COST AND CLEANUP SCRIPTS', (f) => f === 'scripts/check-cost.sh' || f === 'scripts/cleanup.sh'],
  ['28', 'MANUAL BUILD SCRIPT (this file was generated by it)', (f) => f === 'scripts/build-manual.mjs'],
];
const assigned = new Map();
for (const f of files) {
  const g = groups.find(([, , m]) => m(f));
  if (!g) throw new Error(`File not assigned to a section: ${f}`);
  if (!assigned.has(g[0])) assigned.set(g[0], []);
  assigned.get(g[0]).push(f);
}
const bar = '='.repeat(60);
const fileBlock = (f) => `${bar}\nFILE: ${f}\n${bar}\n${read(f).replace(/\s+$/, '')}\n`;

function tree() {
  const lines = ['aegis/'];
  const dirs = {};
  for (const f of files) {
    let d = dirs;
    for (const p of f.split('/')) d = d[p] ??= {};
  }
  const walk = (node, prefix) => {
    const keys = Object.keys(node);
    keys.forEach((k, i) => {
      const last = i === keys.length - 1;
      const kids = Object.keys(node[k]).length > 0;
      lines.push(`${prefix}${last ? '`-- ' : '|-- '}${k}${kids ? '/' : ''}`);
      if (kids) walk(node[k], prefix + (last ? '    ' : '|   '));
    });
  };
  walk(dirs, '');
  lines.push(
    '',
    'Not shown (generated, not hand-authored): node_modules/, dist/, coverage/, package-lock.json (created by `npm install`; verify with `npm ci && npm ls --depth=0`),',
    'and docs/manual/ (the prose sections of this very file). Web build output apps/web/dist is created by `npm run build:web` (verify: dist/index.html exists).',
  );
  return lines.join('\n');
}

const sections = [];
const add = (num, title, body) => sections.push({ num, title, body });
add('1', 'PROJECT OVERVIEW AND EXACT SCOPE', prose('01-overview.txt'));
add('2', 'ARCHITECTURE ANALYSIS BASED ON YOUR ATTACHED IMAGES', prose('02-architecture-analysis.txt'));
add('3', 'FINAL ARCHITECTURE DIAGRAMS (MERMAID)', prose('03-diagrams.txt'));
add('4', 'COMPONENT AND DATA-FLOW EXPLANATIONS', prose('04-components.txt'));
add('5', 'COMPLETE REPOSITORY TREE', tree() + `\n\nFiles included in this manual: ${files.length}`);
add('6', 'PREREQUISITES AND ENVIRONMENT SETUP', prose('06-prerequisites.txt'));
const srcSection = (num, title, intro = '') =>
  add(num, title, `${intro}${intro ? '\n\n' : ''}` + (assigned.get(num) ?? []).map(fileBlock).join('\n'));
srcSection(
  '7',
  'ROOT, SHARED PACKAGE AND CONFIGURATION FILES (every file with its exact repository path)',
  'Section 7 also lists tsconfig, lint, format, test and ignore configuration. package-lock.json is generated: see section 6.5.',
);
add(
  '8',
  'DATABASE SCHEMA, MIGRATIONS AND SEED',
  'Tables: principals, projects, environments, environment_access, assessments, changed_resources, dependencies, policy_findings, impact_scenarios,\nrisk_contributions, agent_runs, recommendations, approval_requests, deployments, verifications, audit_events (+ schema_migrations created by the runner).\nTransactions: each state change and its audit event commit together (withTx). Retention: not automated (see 25). Rollback: *.down.sql, dev/test only.\n\n' +
    (assigned.get('8') ?? []).map(fileBlock).join('\n'),
);
add('9', 'API CONTRACTS', prose('09-api-contract.txt'));
srcSection('10', 'API IMPLEMENTATION (app, config, auth, Azure adapters, LLM provider)');
add(
  '11',
  'AGENT IMPLEMENTATIONS AND ORCHESTRATOR',
  'Execution order: perception -> reasoning -> dependency -> policy -> simulation -> risk -> planning -> reviewer (see 2.3 D4). Perception, policy and risk are mandatory; the others degrade to a partial assessment. Reasoning, reviewer and learning are advisory and never feed the risk score or the gate.\n\n' +
    (assigned.get('11') ?? []).map(fileBlock).join('\n'),
);
add(
  '12',
  'DETERMINISTIC RISK AND POLICY ENGINE',
  prose('12-risk-model.txt') +
    '\n\n(Source: section 11, files apps/api/src/agents/policy.ts, risk.ts, rules/riskRules.ts)',
);
add(
  '13',
  'APPROVAL AND DEPLOYMENT GATE',
  prose('13-gate-approval.txt') +
    '\n\n(Approval request/decision/revoke routes are in apps/api/src/app.ts, section 10.)\n\n' +
    (assigned.get('13') ?? []).map(fileBlock).join('\n'),
);
add(
  '14',
  'POST-DEPLOYMENT VERIFICATION',
  prose('14-verification.txt') + '\n\n' + (assigned.get('14') ?? []).map(fileBlock).join('\n'),
);
srcSection('15', 'FRONTEND IMPLEMENTATION');
srcSection(
  '16',
  'DOCKER AND LOCAL DEVELOPMENT',
  'Docker was NOT available in the build sandbox: Dockerfiles are unbuilt. The API production dependency install and boot (npm ci --omit=dev + tsx) was verified outside Docker.',
);
add(
  '17',
  'AZURE INFRASTRUCTURE AND BICEP',
  prose('17-azure-infra.txt') + '\n\n' + (assigned.get('17') ?? []).map(fileBlock).join('\n'),
);
add(
  '18',
  'AZURE CLI AND PORTAL INSTRUCTIONS',
  prose('18-azure-cli-portal.txt') + '\n\n' + (assigned.get('18') ?? []).map(fileBlock).join('\n'),
);
add(
  '19',
  'AZURE DEVOPS PIPELINE',
  prose('19-pipeline.txt') + '\n\n' + (assigned.get('19') ?? []).map(fileBlock).join('\n'),
);
const results = fs.existsSync(path.join(root, 'docs/manual/generated/test-results.txt'))
  ? fs.readFileSync(path.join(root, 'docs/manual/generated/test-results.txt'), 'utf8').trimEnd()
  : '(no results file)';
add(
  '20',
  'TESTS AND VALIDATION COMMANDS',
  prose('20-tests.txt').replace(
    '(generated by the build script from docs/manual/generated/test-results.txt; see below)',
    results,
  ) +
    '\n\n' +
    (assigned.get('20') ?? []).map(fileBlock).join('\n'),
);
add('21', 'TEN-DAY IMPLEMENTATION SCHEDULE (28 Oct - 6 Nov 2026)', prose('21-schedule.txt'));
add(
  '22',
  'COST ESTIMATES AND BUDGET PROTECTION',
  prose('22-cost.txt') +
    '\n\n' +
    (assigned.get('22') ?? [])
      .filter((f) => f.endsWith('check-cost.sh'))
      .map(fileBlock)
      .join('\n'),
);
add('23', 'TROUBLESHOOTING', prose('23-troubleshooting.txt'));
add('24', 'SECURITY REVIEW', prose('24-security-review.txt'));
add('25', 'PRODUCTION-READINESS ASSESSMENT', prose('25-production-readiness.txt'));
add('26', 'FINAL ACCEPTANCE CHECKLIST', prose('26-acceptance-checklist.txt'));
add(
  '27',
  'CLEANUP AND TEARDOWN',
  prose('27-cleanup.txt') +
    '\n\n' +
    (assigned.get('22') ?? [])
      .filter((f) => f.endsWith('cleanup.sh'))
      .map(fileBlock)
      .join('\n'),
);
add(
  '28',
  'EXPLICIT LIST OF REMAINING LIMITATIONS',
  prose('28-limitations.txt') + '\n\n' + (assigned.get('28') ?? []).map(fileBlock).join('\n'),
);

add('29', 'RESPONSE TO THE EXTERNAL REVIEW OF REVISION 1', prose('29-review-response.txt'));

// two-pass assembly so the table of contents carries real line numbers
const header = (s) => `\n\n${'#'.repeat(72)}\n# SECTION ${s.num}. ${s.title}\n${'#'.repeat(72)}\n\n`;
const bodies = sections.map((s) => header(s) + s.body.trimEnd() + '\n');
const tocFor = (offsetLines) => {
  let line = offsetLines;
  return sections.map((s, i) => {
    const l = line + 4;
    line += bodies[i].split('\n').length - 1;
    return `  Section ${String(s.num).padStart(2)}  line ${String(l).padStart(6)}  ${s.title}`;
  });
};
const titleBlock = `AEGIS BUILD MANUAL - single plain-text file\nGenerated ${new Date().toISOString().slice(0, 10)} by scripts/build-manual.mjs from the real repository (${files.length} files).\nSearch for "SECTION <n>." to jump; search for "FILE: <path>" to find any source file.\n\nTABLE OF CONTENTS\n`;
let toc = tocFor(0);
let head = titleBlock + toc.join('\n') + '\n';
toc = tocFor(head.split('\n').length - 1);
head = titleBlock + toc.join('\n') + '\n';
toc = tocFor(head.split('\n').length - 1);
head = titleBlock + toc.join('\n') + '\n';
const text = head + bodies.join('');
fs.writeFileSync(out, text);

// ---- self-audit
const problems = [];
const blocks = [
  ...text.matchAll(/={60}\nFILE: (.+)\n={60}\n([\s\S]*?)(?=\n={60}\nFILE: |\n\n#{72}\n# SECTION |$)/g),
];
const found = new Map(blocks.map((m) => [m[1], m[2]]));
for (const f of files) {
  if (!found.has(f)) problems.push(`missing in manual: ${f}`);
  else if (found.get(f).replace(/\s+$/, '') !== read(f).replace(/\s+$/, ''))
    problems.push(`content differs: ${f}`);
}
const placeholder =
  /(TODO|FIXME|implement (this )?later|omitted for brevity|add your logic here|same as above|lorem ipsum)/i;
for (const [f, c] of found)
  if (f !== 'scripts/build-manual.mjs' && placeholder.test(c))
    problems.push(`placeholder text in source file ${f}: ${placeholder.exec(c)[0]}`);
for (const n of missingProse) problems.push(`missing prose file: ${n}`);
const mermaid = (text.match(/```mermaid/g) ?? []).length;
console.log(
  `sections=${sections.length} files=${files.length} verified=${found.size} mermaid=${mermaid} lines=${text.split('\n').length} bytes=${Buffer.byteLength(text)} sha256=${crypto.createHash('sha256').update(text).digest('hex').slice(0, 16)}`,
);
if (problems.length) {
  console.error('AUDIT FAILED:\n' + problems.join('\n'));
  process.exit(1);
}
console.log('AUDIT OK: every repository file present byte-for-byte; no placeholder markers in source files');
